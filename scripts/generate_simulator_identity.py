#!/usr/bin/env python3
"""Fingerprint the shared simulator/search source graph used by both binaries."""
import hashlib
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src"
OUTPUT = SOURCE / "simulator_identity_generated.zig"

def generate():
    pending = [SOURCE / "mcts.zig", SOURCE / "search_sim.zig"]
    sources = {}
    while pending:
        path = pending.pop().resolve()
        if path in sources:
            continue
        contents = path.read_bytes()
        sources[path] = contents
        for name in re.findall(rb'@import\("([^"]+\.zig)"\)', contents):
            dependency = path.parent / name.decode()
            if dependency.is_file():
                pending.append(dependency)
    digest = hashlib.sha256()
    digest.update(subprocess.check_output(["zig", "version"]).strip())
    for path, contents in sorted(sources.items()):
        digest.update(str(path.relative_to(ROOT)).encode() + b"\0" + contents + b"\0")
    result = '// Generated by scripts/generate_simulator_identity.py.\npub const fingerprint = "' + digest.hexdigest() + '";\n'
    if not OUTPUT.exists() or OUTPUT.read_text() != result:
        OUTPUT.write_text(result)

if __name__ == "__main__":
    generate()
