#!/usr/bin/env python3
"""Generate the Zig action IDs and Lua editor catalog from the shared JSON."""
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "visualizer/data/action_catalog.json"
ZIG_OUT = ROOT / "src/action_catalog_generated.zig"
LUA_OUT = ROOT / "visualizer/action_catalog.lua"


def validate(catalog):
    specs = catalog.keys()
    if set(specs) != {"warlock", "frost_mage"}:
        raise ValueError("catalog must define warlock and frost_mage")
    lengths = set()
    for spec, actions in catalog.items():
        lengths.add(len(actions))
        ids = [action["id"] for action in actions]
        if ids != list(range(len(actions))):
            raise ValueError(f"{spec} action IDs must be dense and ordered from zero")
        symbols = [action["symbol"] for action in actions]
        if len(symbols) != len(set(symbols)):
            raise ValueError(f"{spec} action symbols must be unique")
        for action in actions:
            if action.get("talent") and (not action["talent"].get("tree") or not isinstance(action["talent"].get("id"), int)):
                raise ValueError(f"{spec}.{action['symbol']} has an invalid talent gate")
        if not actions or actions[0]["name"] != "Idle/Maneuver":
            raise ValueError(f"{spec} must reserve action zero for Idle/Maneuver")
        if sum(action["name"] == "Cancel Cast" for action in actions) != 1:
            raise ValueError(f"{spec} must define Cancel Cast exactly once")
    if len(lengths) != 1:
        raise ValueError("all specs must have the same action count")


def zig_string(value):
    return json.dumps(value, ensure_ascii=True)


def generate_zig(catalog):
    warlock = catalog["warlock"]
    count = len(warlock)
    lines = ["// Generated by scripts/generate_action_catalog.py; edit visualizer/data/action_catalog.json."]
    lines.append("pub const ActionCount: usize = %d;" % count)
    lines.append("pub const MaxChoices: usize = ActionCount * 3;")
    for spec, enum_name in (("warlock", "WarlockAction"), ("frost_mage", "FrostAction")):
        lines.append("pub const %s = enum(u32) {" % enum_name)
        for action in catalog[spec]:
            lines.append("    %s = %d," % (action["symbol"], action["id"]))
        if spec == "warlock":
            lines.extend(["", "    pub const COUNT: usize = ActionCount;"])
        lines.extend(["};", ""])
    for spec in ("warlock", "frost_mage"):
        items = ", ".join(zig_string(action["name"]) for action in catalog[spec])
        lines.append("pub const %s_names = [_][]const u8{ %s };" % (spec, items))
        casts = ", ".join("true" if action.get("starts_cast", False) else "false" for action in catalog[spec])
        lines.append("pub const %s_starts_cast = [_]bool{ %s };" % (spec, casts))
        gates = [action.get("talent", {}) for action in catalog[spec]]
        gate_ids = ", ".join(str(gate.get("id", 0)) for gate in gates)
        gate_trees = ", ".join(zig_string(gate.get("tree", "")) for gate in gates)
        lines.append("pub const %s_talent_gate_ids = [_]u32{ %s };" % (spec, gate_ids))
        lines.append("pub const %s_talent_gate_trees = [_][]const u8{ %s };" % (spec, gate_trees))
    return "\n".join(lines) + "\n"


def generate_lua(catalog):
    lines = ["-- Generated by scripts/generate_action_catalog.py; edit data/action_catalog.json.", "return {"]
    lines.append("    specs = {")
    for spec in ("warlock", "frost_mage"):
        actions = catalog[spec]
        picker_actions = [actions[0]] + [a for a in actions[1:] if a.get("selectable", True)]
        cancel = next(a for a in actions if a["name"] == "Cancel Cast")
        if cancel in picker_actions:
            picker_actions.remove(cancel)
        picker_actions.append(cancel)
        names = ", ".join(json.dumps(action["name"]) for action in picker_actions)
        lines.append("        %s = { %s }," % (spec, names))
    lines.append("    },")
    lines.append("    icons = {")
    all_actions = {}
    for actions in catalog.values():
        for action in actions:
            if action.get("icon"):
                all_actions[action["name"]] = action["icon"]
    for name, icon in sorted(all_actions.items()):
        lines.append("        [%s] = %s," % (json.dumps(name), json.dumps(icon)))
    lines.append("    },")
    lines.append("    names_by_id = {")
    for spec in ("warlock", "frost_mage"):
        entries = ", ".join("[%d] = %s" % (a["id"], json.dumps(a["name"])) for a in catalog[spec])
        lines.append("        %s = { %s }," % (spec, entries))
    lines.append("    },")
    lines.append("    icons_by_id = {")
    for spec in ("warlock", "frost_mage"):
        entries = ", ".join("[%d] = %s" % (a["id"], json.dumps(a.get("icon", "border"))) for a in catalog[spec])
        lines.append("        %s = { %s }," % (spec, entries))
    lines.extend(["    },", "    talent_gates = {"])
    all_actions = {}
    for actions in catalog.values():
        for action in actions:
            if action.get("talent"):
                all_actions[action["name"]] = action["talent"]
    for name, gate in sorted(all_actions.items()):
        lines.append("        [%s] = { tree = %s, id = %d }," % (json.dumps(name), json.dumps(gate["tree"]), gate["id"]))
    lines.extend(["    },", "}"])
    return "\n".join(lines) + "\n"


def main():
    catalog = json.loads(SOURCE.read_text())
    validate(catalog)
    ZIG_OUT.write_text(generate_zig(catalog))
    LUA_OUT.write_text(generate_lua(catalog))


if __name__ == "__main__":
    main()
