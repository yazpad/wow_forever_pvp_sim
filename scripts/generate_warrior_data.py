#!/usr/bin/env python3
"""Generate staged Forever warrior data from checked-in, hash-pinned sources.

No network or external checkout is required. The UI snapshot supplies layout and
tooltip parameters; the newer client table supplies canonical base spell IDs.
Tooltip parameters are not automatically treated as proven runtime mechanics.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "data/warrior_sources"


def generate():
    manifest = json.loads((SOURCES / "manifest.json").read_text())
    for name, entry in manifest["files"].items():
        actual = hashlib.sha256((SOURCES / name).read_bytes()).hexdigest()
        if actual != entry["sha256"]:
            raise ValueError(f"Pinned source changed: {name}; audit before updating manifest")
    trees = json.loads((SOURCES / "talents.json").read_text())
    spells = (SOURCES / "spell_data.go").read_text()
    output = {}
    definitions = []
    used_ids = set()
    bit_offset = 0
    for tree_idx, tree in enumerate(trees):
        talents = []
        by_location = {}
        for item in tree["talents"]:
            field = item["fieldName"]
            name = field[0].upper() + field[1:]
            match = re.search(r"\t" + name + r": shared.SpellDataTable\{\n(.*?)\n\t\},", spells, re.S)
            if not match:
                raise ValueError(f"No client spell table for {name}")
            ids = [int(x) for x in re.findall(r"SpellID: (\d+)", match[1])]
            # Talent-granted active abilities have additional spell ranks. Talent
            # ranks are determined by the tree, not by the active spell's ranks.
            maximum = item["maxPoints"]
            if len(ids) < maximum or not all(ids):
                raise ValueError(f"Incomplete client ranks for {name}")
            spell_id = ids[0]
            if spell_id in used_ids:
                raise ValueError(f"Duplicate talent ID {spell_id}")
            used_ids.add(spell_id)
            row, col = item["location"]["rowIdx"], item["location"]["colIdx"]
            descriptions = {}
            for rank, values in enumerate(item["ranks"], 1):
                descriptions[str(rank)] = item["description"].format(*values)
            if len(descriptions) != maximum:
                raise ValueError(f"Incomplete descriptions for {name}")
            supported = field in {
                "improvedHeroicStrike", "improvedTacticalMastery", "boundlessRage",
                "improvedCharge", "improvedIntercept", "vanguard", "mortalStrike",
                "improvedRend", "improvedOverpower", "bloodthirst", "deathWish", "cruelty", "unbridledWrath",
                "enrage", "flurry", "precision", "dualWieldSpecialization",
            }
            talent = {
                "id": spell_id, "key": field, "name": item["name"],
                "icon": item.get("icon") or Path(item["iconUrl"]).stem,
                "row": row, "col": col,
                "max_ranks": maximum, "descriptions": descriptions,
                "requires": [], "required_points": row * 5,
                "rank_spell_ids": ids[:maximum],
                "runtime_supported": supported,
                "runtime_support": "full" if supported else ("partial" if field in {"dualWieldSpecialization", "ragingBlows"} else "none"),
                "source_status": "pinned_reference; arena effect implemented" if supported else "pinned_reference; runtime effect audit pending",
            }
            # Pack each talent wholly within a u32 so SIMD unpacking never needs
            # a cross-word shift. Four words suffice for the complete tree.
            width = maximum.bit_length()
            if bit_offset % 32 + width > 32:
                bit_offset = (bit_offset // 32 + 1) * 32
            definitions.append((field, spell_id, maximum, tree_idx, row, bit_offset, width, item))
            bit_offset += width
            talents.append(talent)
            by_location[(row, col)] = talent
        for talent, item in zip(talents, tree["talents"]):
            if req := item.get("prereqLocation"):
                parent = by_location[(req["rowIdx"], req["colIdx"])]
                talent["requires"] = [{"id": parent["id"], "qty": parent["max_ranks"]}]
        output[tree["name"]] = {"id": tree["name"].lower(), "name": tree["name"], "talents": talents}
    if bit_offset > 128 or len(definitions) != 53:
        raise ValueError("Warrior layout changed; audit packing and talent count")
    lines = [
        "// Generated by scripts/generate_warrior_data.py. Do not edit.",
        'pub const client_build = "' + manifest["target_client_build"] + '";',
        "pub const Talent = enum(u8) {",
    ]
    lines += [f"    {field}," for field, *_ in definitions]
    lines += ["};", "pub const Definition = struct {", "    id: u32,", "    max_rank: u8,",
              "    tree: u8,", "    row: u8,", "    word: u8,", "    shift: u5,", "    bits: u5,",
              "    prerequisite: ?Talent = null,", "};", "pub const definitions = [_]Definition{"]
    for field, spell_id, maximum, tree_idx, row, offset, width, item in definitions:
        parent = ""
        if req := item.get("prereqLocation"):
            parent_item = next(t for t in trees[tree_idx]["talents"] if t["location"] == req)
            parent = f", .prerequisite = .{parent_item['fieldName']}"
        lines.append(f"    .{{ .id = {spell_id}, .max_rank = {maximum}, .tree = {tree_idx}, .row = {row}, .word = {offset // 32}, .shift = {offset % 32}, .bits = {width}{parent} }},")
    lines += ["};", ""]
    return {
        ROOT / "visualizer/data/talents_warrior.json": json.dumps(output, indent=2) + "\n",
        ROOT / "src/warrior_data_generated.zig": "\n".join(lines),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    for path, contents in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f"Stale generated file: {path.relative_to(ROOT)}")
        elif not path.exists() or path.read_text() != contents:
            path.write_text(contents)


if __name__ == "__main__":
    main()
