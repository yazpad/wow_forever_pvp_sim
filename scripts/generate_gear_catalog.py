"""Generate native catalog data from the editor's canonical offline JSON."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for source_path, destination_path in [
    ('data/vanilla_gear.json', 'src/gear_catalog_generated.zig'),
    ('data/stat_sources/forever_level60.json', 'src/stat_reference_generated.zig'),
]:
    source = (root / source_path).read_text()
    if source_path == 'data/vanilla_gear.json':
        combined = json.loads(source)
        combined['items'] += json.loads((root / 'data/warrior_gear.json').read_text())['items']
        combined['items'] += json.loads((root / 'data/item_actives.json').read_text())['items']
        source = json.dumps(combined, indent=2) + '\n'
    output = '// Generated by scripts/generate_gear_catalog.py; do not edit.\npub const json = ' + json.dumps(source, ensure_ascii=True) + ';\n'
    destination = root / destination_path
    if args.check:
        if not destination.exists() or destination.read_text() != output:
            raise SystemExit(f'Native data is stale: {destination_path}; run python3 scripts/generate_gear_catalog.py')
    else:
        destination.write_text(output)
